class LTXDirectorService:
    """Multi-segment long-video generation with native audio/dialogue."""

    def __init__(self, model_manager, config):
        self.manager = model_manager
        self.config = config

    def check_models(self) -> list:
        """Missing model files, if any."""
        missing = []
        for sub, fname in REQUIRED_MODELS:
            if not (self.config.paths.models_dir / sub / fname).exists():
                missing.append(f"{sub}/{fname}")
        if not any((self.config.paths.models_dir / "diffusion_models" / c).exists()
                   for c in DEV_GGUF_CANDIDATES):
            missing.append(f"diffusion_models/{DEV_GGUF_CANDIDATES[0]}")
        return missing

    # ── segment building ───────────────────────────────────────────────

    @staticmethod
    def build_segments(segments: list[dict], fps: int = 24):
        """segments: [{prompt, dialogue?, image_path, seconds}] →
        (timeline_json, local_prompts, lengths_csv, guides_csv, total_frames)."""
        tl, prompts, lengths = [], [], []
        start = 0.0
        for i, seg in enumerate(segments):
            frames = max(24, int(round(float(seg["seconds"]) * fps)))
            text = seg["prompt"].strip()
            if seg.get("dialogue"):
                text += f"\n{seg['dialogue'].strip()}"
            fname = Path(seg["image_path"]).name
            tl.append({
                "id": f"aidir{i}{random.randint(1000, 9999)}",
                "start": start,
                "length": float(frames),
                "prompt": text,
                "type": "image",
                "imageFile": fname,
                "imageB64": f"/api/view?filename={fname}&type=input&subfolder=",
            })
            prompts.append(text)
            lengths.append(str(frames))
            start += frames
        timeline = json.dumps({"segments": tl, "audioSegments": []})
        guides = ",".join("1.00" for _ in segments)
        return timeline, " | ".join(prompts), ",".join(lengths), guides, int(start)

    # ── workflow assembly ──────────────────────────────────────────────

    def _inject_extra_loras(self, graph: dict, extra: list[tuple[str, float]]):
        """Chain additional LoraLoaderModelOnly nodes into the top-level MODEL
        path (between the template's last LoRA and the 'Anything Everywhere'
        MODEL broadcast), so every sampler downstream sees them."""
        loras_dir = self.config.paths.models_dir / "loras"
        extra = [(f, w) for f, w in extra if (loras_dir / f).exists()]
        if not extra:
            return
        # the AE node that broadcasts MODEL — its input link is the chain end
        ae = next((n for n in graph["nodes"]
                   if n["type"].startswith("Anything Everywhere")
                   and any(i.get("type") == "MODEL" and i.get("link") is not None
                           for i in n.get("inputs", []))), None)
        if ae is None:
            logger.warning("[LTXDirector] no MODEL broadcast node — extra LoRAs skipped")
            return
        ae_input = next(i for i in ae["inputs"]
                        if i.get("type") == "MODEL" and i.get("link") is not None)
        tail_link = ae_input["link"]
        links = graph["links"]
        rec = next(l for l in links if l[0] == tail_link)
        origin_id, origin_slot = rec[1], rec[2]
        origin_node = next(n for n in graph["nodes"] if n["id"] == origin_id)

        nid = graph.get("last_node_id", 0)
        lid = graph.get("last_link_id", 0)
        prev_id, prev_slot = origin_id, origin_slot
        for fname, weight in extra:
            nid += 1
            lid += 1
            # link from previous chain end into this new lora node
            if prev_id == origin_id:
                # rewire the origin's output away from the AE link
                out = origin_node["outputs"][origin_slot]
                out["links"] = [l for l in (out.get("links") or [])
                                if l != tail_link] + [lid]
            else:
                prev_node = next(n for n in graph["nodes"] if n["id"] == prev_id)
                prev_node["outputs"][0]["links"] = [lid]
            links.append([lid, prev_id, prev_slot, nid, 0, "MODEL"])
            graph["nodes"].append({
                "id": nid, "type": "LoraLoaderModelOnly", "pos": [0, 0],
                "size": [270, 82], "flags": {}, "order": 0, "mode": 0,
                "inputs": [{"name": "model", "type": "MODEL", "link": lid}],
                "outputs": [{"name": "MODEL", "type": "MODEL", "links": []}],
                "properties": {"Node name for S&R": "LoraLoaderModelOnly"},
                "widgets_values": [fname, weight],
            })
            logger.info(f"[LTXDirector] + LoRA {fname} @{weight}")
            prev_id, prev_slot = nid, 0
        # last new node feeds the AE broadcast via the original link id
        last_node = graph["nodes"][-1]
        last_node["outputs"][0]["links"] = [tail_link]
        rec[1], rec[2] = prev_id, 0
        graph["last_node_id"] = nid
        graph["last_link_id"] = lid

    def build_workflow(self, segments: list[dict], width: int = 1280,
                       height: int = 704, fps: int = 24,
                       style_prompt: str = "",
                       extra_loras: Optional[list] = None) -> dict:
        """Patch the template with real segments and convert to API format.
        Segments are split across the template's two chained LTXDirector
        nodes (first half / second half)."""
        graph = json.loads(TEMPLATE_PATH.read_text(encoding="utf-8"))

        # User has selected their available models directly in the template JSON,
        # so we bypass the dynamic model substitution that used to overwrite them.

        # chain in the motion/detail LoRAs (+ any per-project ones)
        self._inject_extra_loras(
            graph, EXTRA_LORAS + list(extra_loras or []))

        # Proven recipe (usman's 25-min 720p run): 5-6 segments x ~5-6s =
        # ~30s per director node, up to 2 directors per workflow.
        if len(segments) > 12:
            raise ValueError(
                f"LTX Director supports at most 12 scenes per video "
                f"(6 per director node) — this project has {len(segments)}. "
                f"Reduce the scene count or use the clip-by-clip engine.")

        director_nodes = [n for n in graph["nodes"] if n["type"] == "LTXDirector"]
        director_nodes.sort(key=lambda n: n["id"])
        if len(segments) <= 6:
            # SINGLE-DIRECTOR mode: everything fits one node. Remove the
            # second director + its sampler subgraph so ComfyUI never runs
            # them, and bypass the joiners so branch 1 passes straight through.
            parts = [segments]
            d2 = director_nodes[1]
            d2_links = {l for o in (d2.get("outputs") or [])
                        for l in (o.get("links") or [])}
            drop = {id(d2)}
            for n in graph["nodes"]:
                if any(i.get("link") in d2_links for i in (n.get("inputs") or [])):
                    drop.add(id(n))          # director 2's sampler subgraph
                elif n["type"] in ("ImageBatchMulti", "AudioConcatenate"):
                    n["mode"] = 4            # bypass: image_1/audio1 pass through
            graph["nodes"] = [n for n in graph["nodes"] if id(n) not in drop]
            director_nodes = director_nodes[:1]
        else:
            # split across the two chained director nodes
            half = (len(segments) + 1) // 2
            parts = [segments[:half], segments[half:]]
        for node, part in zip(director_nodes, parts):
            tl, prompts, lengths, guides, total = self.build_segments(part, fps)
            wv = node["widgets_values"]
            if style_prompt:
                wv[0] = style_prompt
            wv[1] = total                # duration_frames
            wv[2] = round(total / fps)   # duration_seconds
            wv[3] = tl                   # timeline_data
            wv[4] = prompts              # local_prompts
            wv[5] = lengths              # segment_lengths
            # guide_strength MUST have exactly one entry per segment — the
            # template ships 5; a mismatched count degrades generation badly
            wv[7] = guides
            wv[9] = fps                  # frame_rate
            # Do NOT overwrite width and height (wv[11], wv[12]) to preserve
            # the user's native template resolution (e.g. 720p instead of 704p)
            # which prevents "trash" generation quality.

        # unique output prefix
        for n in graph["nodes"]:
            if n["type"] == "VHS_VideoCombine":
                n["widgets_values"]["filename_prefix"] = \
                    f"aidir_ltxdir/{int(time.time())}"

        object_info = self._object_info()
        api = GraphConverter(graph, object_info).convert()
        return api

    def _object_info(self) -> dict:
        with urllib.request.urlopen("http://127.0.0.1:8188/object_info",
                                    timeout=30) as resp:
            return json.loads(resp.read())

    # ── orchestration ──────────────────────────────────────────────────

    def generate(self, segments: list[dict], output_path: str,
                 width: int = 1280, height: int = 704, fps: int = 24,
                 style_prompt: str = "", timeout: float = 14400,
                 extra_loras: Optional[list] = None) -> str:
        """Full run: stage images → build workflow → submit → collect video.
        `segments`: [{prompt, dialogue?, image_path, seconds}]."""
        from app.services.comfyui_client import ComfyUIClient

        missing = self.check_models()
        if missing:
            raise RuntimeError(f"LTX Director models missing: {missing}")

        client = ComfyUIClient()
        if not client.ensure_running():
            raise RuntimeError("ComfyUI is not running")

        # stage reference images into ComfyUI/input
        COMFYUI_INPUT.mkdir(parents=True, exist_ok=True)
        for seg in segments:
            src = Path(seg["image_path"])
            if not src.exists():
                raise FileNotFoundError(f"Segment image missing: {src}")
            dst = COMFYUI_INPUT / src.name
            if not dst.exists() or dst.stat().st_size != src.stat().st_size:
                shutil.copy2(src, dst)

        # everything else out of VRAM — this is the biggest job we run
        try:
            self.manager.unload()
        except Exception:
            pass
        client.free_vram()
        time.sleep(2)
        client.free_vram()

        wf = self.build_workflow(segments, width, height, fps, style_prompt,
                                 extra_loras=extra_loras)
        logger.info(f"[LTXDirector] Submitting {len(segments)} segments "
                    f"({sum(float(s['seconds']) for s in segments):.0f}s total) "
                    f"as {len(wf)} API nodes")
        prompt_id = client.submit(wf)
        history = client.wait_for_completion(prompt_id, timeout=timeout)
        return client.collect_output(history, output_path)

    def _generate_chunked(self, segments: list[dict], project_dir,
                          out_path: str, chunk_size: int = 5,
                          extra_loras: Optional[list] = None) -> str:
        """Long videos via MULTIPLE ComfyUI calls, then concat — the proven way
        to exceed one director's length while staying inside usman's ~6s-segment
        recipe. Runs ONE single-director LTX call per chunk of `chunk_size`
        segments (5 × ~5s ≈ 25s per call ≈ 600 frames, within usman's proven
        720), saves each to ltx_parts/part_XX.mp4 immediately, then ffmpeg-concats
        every part into one video. There is NO overall length cap — a 3-4 min
        video is just ~8-10 of these ~25s passes stitched together. Resumable at
        PART granularity: a crash/power cut only redoes the part mid-render;
        finished parts are skipped."""
        import os
        chunks = [segments[i:i + chunk_size]
                  for i in range(0, len(segments), chunk_size)]
        if len(chunks) > 1 and len(chunks[-1]) == 1:
            # a lone trailing segment renders poorly — fold it into the
            # previous chunk (7 segments splits 4+3 across the two directors)
            chunks[-2].extend(chunks.pop())

        parts_dir = Path(project_dir) / "ltx_parts"
        parts_dir.mkdir(parents=True, exist_ok=True)
        part_files = []
        for i, chunk in enumerate(chunks):
            part = parts_dir / f"part_{i:02d}.mp4"
            if part.exists() and part.stat().st_size > 100_000:
                logger.info(f"[LTXDirector] director {i + 1}/{len(chunks)} "
                            f"already rendered — resuming past it")
            else:
                secs = sum(float(s["seconds"]) for s in chunk)
                logger.info(f"[LTXDirector] director {i + 1}/{len(chunks)}: "
                            f"{len(chunk)} segments ({secs:.0f}s)")
                # render to a temp name and swap in atomically: a power cut
                # mid-copy must never leave a corrupt part_XX.mp4 behind that
                # a later resume would silently trust
                tmp = parts_dir / f"part_{i:02d}.tmp.mp4"
                if tmp.exists():
                    tmp.unlink()
                self.generate(chunk, str(tmp), extra_loras=extra_loras)
                os.replace(tmp, part)
            part_files.append(part)

        lst = parts_dir / "concat.txt"
        lst.write_text("".join(f"file '{p.as_posix()}'\n" for p in part_files),
                       encoding="utf-8")
        subprocess.run(
            [str(self.config.paths.ffmpeg_bin), "-y", "-f", "concat",
             "-safe", "0", "-i", str(lst), "-c", "copy", str(out_path)],
            check=True, capture_output=True)
        return str(out_path)

    def generate_for_project(self, project_id: str) -> str:
        """Build segments from the project's scenes (uses each scene's still
        image + prompt + narration line as spoken dialogue) and run."""
        from app.database import get_session, Project, Scene, SceneStatus

        session = get_session()
        try:
            project = session.query(Project).get(project_id)
            if not project:
                raise ValueError(f"Project {project_id} not found")
            scenes = session.query(Scene).filter(
                Scene.project_id == project_id
            ).order_by(Scene.scene_number).all()

            images_dir = self.config.paths.projects_dir / project_id / "images"
            from app.services import master_director
            guidance_plan = []
            segments = []
            for idx, s in enumerate(scenes):
                # reference still, in priority order: user-pinned still →
                # generation output/thumbnail → batch-phase still file
                notes = s.director_notes or {}
                img = None
                for cand in (notes.get("pinned_still"), notes.get("pinned_image")):
                    if cand and Path(cand).exists():
                        img = cand
                        break
                if not img:
                    for g in reversed(s.generations or []):
                        for cand in (g.output_path, g.thumbnail_path):
                            if cand and Path(cand).exists() and \
                                    Path(cand).suffix.lower() in (".png", ".jpg", ".jpeg", ".webp"):
                                img = cand
                                break
                        if img:
                            break
                if not img:
                    stills = sorted(images_dir.glob(f"scene_{s.scene_number:03d}_*.png"))
                    if stills:
                        img = str(stills[-1])
                if not img:
                    continue
                # Song projects: the song is the soundtrack — characters must
                # NOT speak the lyric lines; keep native ambience only.
                dialogue = ""
                if s.narration_text and \
                        getattr(project, "project_type", "song") != "song":
                    dialogue = f'The narrator says: "{s.narration_text.strip()}"'
                # Master-director guidance: reuse the guidance saved at scene
                # planning; older scenes without one get it here (and it is
                # saved back so resume sees the identical storyboard).
                guidance = notes.get("director_guidance")
                if not guidance:
                    guidance = master_director.guidance_for(
                        idx, len(scenes), str(notes.get("section") or "verse"),
                        project_id)
                    new_notes = dict(notes)
                    new_notes["director_guidance"] = guidance
                    s.director_notes = new_notes
                guidance_plan.append(guidance)
                segments.append({
                    "prompt": master_director.apply_cue(s.prompt, guidance),
                    "dialogue": dialogue,
                    "image_path": img,
                    "seconds": float(s.duration or 5.0),
                })
            session.commit()   # persist any newly assigned guidance
            try:
                master_director.save_plan(
                    self.config.paths.projects_dir / project_id, guidance_plan)
            except Exception as g_err:
                logger.warning(f"[LTXDirector] guidance save failed: {g_err}")
            if len(segments) < 2:
                raise ValueError(
                    "LTX Director needs at least 2 scenes with a still image "
                    "each (generate stills first, or pin images per scene)")

            # per-project LoRAs ride along in the director's model chain
            proj_loras = []
            ids = project.default_lora_ids or []
            weights = project.default_lora_weights or []
            for i, f in enumerate(ids):
                w = weights[i] if i < len(weights) else 0.7
                proj_loras.append((Path(f).name, float(w)))

            project_dir = self.config.paths.projects_dir / project_id
            out = str(project_dir / "ltx_director_render.mp4")
            if len(segments) <= 5:
                # short video — a single usman-proven director pass, no concat
                result = self.generate(segments, out, extra_loras=proj_loras)
            else:
                # LONGER video — split into ~25s usman-proven passes (one
                # ComfyUI call each), saved to ltx_parts/part_XX.mp4 as they
                # finish, then concatenated. This is how a 3-4 min video is
                # built: ~8-10 stitched passes. Resume skips finished parts.
                result = self._generate_chunked(segments, project_dir, out,
                                                extra_loras=proj_loras)
            project.output_path = result
            session.commit()
            return result
        finally:
            session.close()
