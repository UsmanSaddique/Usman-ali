# ── UI-graph → API-prompt conversion ───────────────────────────────────────

class GraphConverter:
    """Converts a ComfyUI UI-format graph (with subgraphs, Set/Get nodes,
    'Anything Everywhere' broadcasts, reroutes and bypassed nodes) into the
    flat API prompt format {id: {class_type, inputs}}."""

    def __init__(self, graph: dict, object_info: dict):
        self.graph = graph
        self.object_info = object_info
        self.subgraph_defs = {
            s["id"]: s for s in (graph.get("definitions") or {}).get("subgraphs", [])
        }
        self.nodes: dict = {}      # flat_id -> node dict (expanded)
        self.links: dict = {}      # link_id -> (origin_flat_id, origin_slot)
        self._uid = 0

    def _next_id(self) -> str:
        self._uid += 1
        return f"n{self._uid}"

    # ── expansion ──────────────────────────────────────────────────────

    def convert(self) -> dict:
        self._expand(self.graph["nodes"], self.graph.get("links", []),
                     outer_input_map={}, link_ns="top")
        self._resolve_set_get()
        self._resolve_everywhere()
        return self._emit()

    def _expand(self, nodes: list, links: list, outer_input_map: dict,
                link_ns: str):
        """Flatten one graph level. outer_input_map maps this level's
        subgraph-input slot index -> (origin_flat_id, origin_slot) in the
        parent. Returns {output_slot_index: (flat_id, slot)} for -20 targets."""
        id_map = {}      # local node id -> flat id
        sub_instances = []
        for n in nodes:
            if n["type"] in self.subgraph_defs:
                sub_instances.append(n)
                continue
            fid = self._next_id()
            id_map[n["id"]] = fid
            self.nodes[fid] = copy.deepcopy(n)

        # normalize link records (top-level uses arrays, subgraphs use dicts)
        def rec(l):
            if isinstance(l, dict):
                return (l["id"], l["origin_id"], l["origin_slot"],
                        l["target_id"], l["target_slot"])
            return (l[0], l[1], l[2], l[3], l[4])

        out_map = {}
        pending_sub_links = []   # links touching a subgraph instance
        for l in links:
            lid, o_id, o_slot, t_id, t_slot = rec(l)
            key = f"{link_ns}:{lid}"
            if o_id == -10:                       # from subgraph input
                src = outer_input_map.get(o_slot)
                if src:
                    self.links[key] = src
            elif o_id in id_map:
                self.links[key] = (id_map[o_id], o_slot)
            else:
                pending_sub_links.append((lid, o_id, o_slot, t_id, t_slot))
            if t_id == -20 and key in self.links:  # to subgraph output
                out_map[t_slot] = self.links[key]

        # expand each subgraph instance
        for inst in sub_instances:
            sdef = self.subgraph_defs[inst["type"]]
            # 1. map DEF input slots -> parent link sources. Match by NAME:
            #    instances may omit inputs (e.g. an unlinked frame_rate), so
            #    positional mapping silently mis-wires everything after the gap.
            by_name = {}
            for iput in inst.get("inputs", []):
                l = iput.get("link")
                if l is not None:
                    src = self.links.get(f"{link_ns}:{l}")
                    if src:
                        by_name[iput["name"]] = src
            inst_in_map = {}
            for d_idx, d_input in enumerate(sdef.get("inputs", [])):
                src = by_name.get(d_input.get("name"))
                if src:
                    inst_in_map[d_idx] = src
            ns = f"{link_ns}/{inst['id']}"
            sub_out = self._expand(sdef["nodes"], sdef.get("links", []),
                                   inst_in_map, ns)
            # 2. instance output slot i -> inner source; register under the
            #    parent link ids attached to that output
            for idx, oput in enumerate(inst.get("outputs", [])):
                src = sub_out.get(idx)
                if not src:
                    continue
                for l in (oput.get("links") or []):
                    self.links[f"{link_ns}:{l}"] = src

        # unresolved forward references (source was a subgraph, now known)
        for lid, o_id, o_slot, t_id, t_slot in pending_sub_links:
            key = f"{link_ns}:{lid}"
            if key in self.links and t_id == -20:
                out_map[t_slot] = self.links[key]

        # record namespace on nodes for input resolution later
        for n_id, fid in id_map.items():
            self.nodes[fid]["_ns"] = link_ns
        return out_map

    # ── virtual node resolution ────────────────────────────────────────

    def _source_of(self, node: dict, input_index: int = 0):
        ns = node.get("_ns", "top")
        inputs = node.get("inputs", [])
        if input_index >= len(inputs):
            return None
        l = inputs[input_index].get("link")
        if l is None:
            return None
        return self.links.get(f"{ns}:{l}")

    def _resolve_set_get(self):
        """SetNode registers its input under a title; GetNode outputs it."""
        registry = self._registry = {}
        for fid, n in list(self.nodes.items()):
            if n["type"] == "SetNode":
                title = (n.get("widgets_values") or [n.get("title", "")])[0]
                src = self._source_of(n, 0)
                if src:
                    registry[str(title)] = src
        for fid, n in list(self.nodes.items()):
            if n["type"] == "GetNode":
                title = (n.get("widgets_values") or [n.get("title", "")])[0]
                src = registry.get(str(title))
                if not src:
                    continue
                ns = n.get("_ns", "top")
                for oput in n.get("outputs", []):
                    for l in (oput.get("links") or []):
                        self.links[f"{ns}:{l}"] = src

    def _resolve_everywhere(self):
        """'Anything Everywhere' broadcasts its input to every unlinked input
        of the same TYPE anywhere in the graph."""
        broadcasts = {}   # type -> (fid, slot)
        for fid, n in self.nodes.items():
            if n["type"].startswith("Anything Everywhere"):
                for idx, iput in enumerate(n.get("inputs", [])):
                    src = self._source_of(n, idx)
                    if src:
                        broadcasts[iput.get("type", "*")] = src
        if not broadcasts:
            return
        for fid, n in self.nodes.items():
            if n["type"] in _VIRTUAL_TYPES or n["type"].startswith("Anything Everywhere"):
                continue
            ns = n.get("_ns", "top")
            for iput in n.get("inputs", []):
                if iput.get("link") is None and iput.get("type") in broadcasts:
                    # synthesize a link
                    self._uid += 1
                    fake = f"ue{self._uid}"
                    iput["link"] = fake
                    self.links[f"{ns}:{fake}"] = broadcasts[iput["type"]]

    def _trace(self, src, want_type: Optional[str] = None, depth: int = 0):
        """Follow a (fid, slot) source through virtual/bypassed nodes until a
        real emitting node is reached."""
        if src is None or depth > 40:
            return None
        fid, slot = src
        n = self.nodes.get(fid)
        if n is None:
            return None
        ntype = n["type"]
        mode = n.get("mode", 0)
        if ntype == "Reroute":
            return self._trace(self._source_of(n, 0), want_type, depth + 1)
        if ntype == "GetNode":
            # GetNode has no inputs — resolve through the Set/Get registry
            title = (n.get("widgets_values") or [n.get("title", "")])[0]
            return self._trace(getattr(self, "_registry", {}).get(str(title)),
                               want_type, depth + 1)
        if ntype == "SetNode":
            return self._trace(self._source_of(n, 0), want_type, depth + 1)
        if mode in (2, 4):   # muted/bypassed: pass through matching input type
            out_type = None
            outs = n.get("outputs", [])
            if slot < len(outs):
                out_type = outs[slot].get("type")
            for idx, iput in enumerate(n.get("inputs", [])):
                if iput.get("type") == out_type or out_type in ("*", None):
                    nxt = self._source_of(n, idx)
                    if nxt:
                        return self._trace(nxt, want_type, depth + 1)
            return None
        return (fid, slot)

    # ── emission ───────────────────────────────────────────────────────

    def _widget_input_names(self, class_type: str) -> list:
        """Ordered input names that consume widgets_values entries."""
        info = self.object_info.get(class_type)
        if not info:
            return []
        names = []
        for section in ("required", "optional"):
            for name, spec in (info["input"].get(section) or {}).items():
                type_spec = spec[0] if isinstance(spec, list) and spec else spec
                opts = spec[1] if isinstance(spec, list) and len(spec) > 1 and isinstance(spec[1], dict) else {}
                is_widget = isinstance(type_spec, list) or (
                    isinstance(type_spec, str)
                    and type_spec in ("INT", "FLOAT", "STRING", "BOOLEAN", "COMBO"))
                if opts.get("forceInput"):
                    is_widget = False
                names.append((name, is_widget))
        return names

    def _emit(self) -> dict:
        prompt = {}
        for fid, n in self.nodes.items():
            ntype = n["type"]
            if ntype in _VIRTUAL_TYPES or ntype.startswith("Anything Everywhere") \
                    or ntype in self.subgraph_defs:
                continue
            if n.get("mode", 0) in (2, 4):
                continue
            api_inputs = {}
            ns_inputs = n.get("inputs", [])

            # linked inputs
            linked_names = set()
            for idx, iput in enumerate(ns_inputs):
                if iput.get("link") is None:
                    continue
                src = self._trace(self._source_of(n, idx))
                if src:
                    api_inputs[iput["name"]] = [src[0], src[1]]
                    linked_names.add(iput["name"])

            # widget inputs
            wv = n.get("widgets_values")
            if isinstance(wv, dict):
                for k, v in wv.items():
                    if k not in linked_names and not k.startswith("videopreview"):
                        api_inputs[k] = v
            elif isinstance(wv, list):
                names = self._widget_input_names(ntype)
                wi = 0
                for name, is_widget in names:
                    if not is_widget:
                        continue
                    if wi >= len(wv):
                        break
                    val = wv[wi]
                    wi += 1
                    if name not in linked_names:
                        api_inputs[name] = val
                    # skip UI-only seed-control companion value
                    if name in ("seed", "noise_seed") and wi < len(wv) \
                            and isinstance(wv[wi], str) \
                            and wv[wi] in _SEED_CONTROL_VALUES:
                        wi += 1
            prompt[fid] = {"class_type": ntype, "inputs": api_inputs}
        return prompt


